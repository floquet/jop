def form_input(name):
    return f'\t\\input{{\\pSections/"forms-individual/sec-forms-{name}.tex"}}\n'


def make_injector(accounts, written):
    """Count readable account records and render the curated form order."""
    available = {path.stem.removeprefix("sec-forms-") for path in written}
    selected = {
        cost: {sub: [name for name in names if name in available]
               for sub, names in groups.items()}
        for cost, groups in CURATED.items()
    }
    missing = [name for groups in CURATED.values() for names in groups.values()
               for name in names if name not in available]
    for name in missing:
        print(f"Not included in summary (slide missing): {name}", file=sys.stderr)

    analyzed = Counter(".".join(account.split(".")[:2]) for account in accounts)
    subcodes = {}
    for account in accounts:
        parts = account.split(".")
        cost = ".".join(parts[:2])
        subcodes.setdefault(cost, set()).add(".".join(parts[:3]))
    selected_count = sum(len(names) for groups in selected.values()
                         for names in groups.values())
    present_costs = [cost for cost in CURATED if cost in analyzed]
    present_costs += sorted(set(analyzed) - set(present_costs))
    chunks = [
        '% \\input{\\pSections/"sec-forms.tex"}\n',
        '\\typeout{\\enumContent \\pSections/"sec-forms.tex"}\n\n',
        f'% Generated by: {Path(__file__).resolve()}\n',
        f'% Generated at: {datetime.datetime.now().astimezone().isoformat(timespec="seconds")}\n\n',
        '%%%   %%%   %%%   %%%   %%%   %%%   %%%\n',
        '\\section{Summary of Survey Forms}\n',
        '\\begin{frame}{Census}\n',
        f'  {len(accounts)} forms analyzed\\par\n',
        f'  {len(present_costs)} cost codes\\par\n',
        '  \\begin{itemize}\n',
    ]
    chunks.extend(f'    \\item \\hyperlink{{sec:{cost}}}{{{cost}}}\n'
                  for cost in present_costs)
    chunks.extend(['  \\end{itemize}\n', '\\end{frame}\n\n'])
    for cost in present_costs:
        groups = selected.get(cost, {})
        present_subcodes = [sub for sub in groups if sub in subcodes[cost]]
        present_subcodes += sorted(subcodes[cost] - set(present_subcodes))
        chunks.extend([
            '%%%   %%%   %%%   %%%   %%%\n',
            f'\\subsection{{Cost Code {cost}}}\\hypertarget{{sec:{cost}}}{{}}\n',
            '\\begin{frame}{Census}\n',
            f'  {analyzed[cost]} forms analyzed\\par\n',
            f'  {len(present_subcodes)} cost subcodes\\par\n',
        ])
        if present_subcodes:
            chunks.append('  \\begin{itemize}\n')
            chunks.extend(f'    \\item \\hyperlink{{sec:{sub}}}{{{sub}}}\n'
                          for sub in present_subcodes)
            chunks.append('  \\end{itemize}\n')
        chunks.append('\\end{frame}\n')
        for sub in present_subcodes:
            chunks.extend([
                '\n%%%   %%%   %%%\n',
                f'\\subsubsection{{Cost Code {sub}}}\\hypertarget{{sec:{sub}}}{{}}\n',
            ])
            chunks.extend(form_input(name) for name in groups.get(sub, []))
        chunks.append('\n')
    chunks.append('\\endinput  %  -  -  -  -  -  -  -  -  -  -  -  -  -  -  -\n')
    return ''.join(chunks), selected_count, len(missing)


def main():
    files = sorted(path for path in INPUT.glob("*.json") if path.is_file())
    if not files:
        raise SystemExit(f"No JSON files found in {INPUT}")
    documents = []
    accounts = []
    errors = []
    for path in files:
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
            source = str(document["metadata"]["source_file"])
            match = ACCOUNT_RE.search(source)
            if match is None:
                raise ValueError(f"No account number in source_file: {source}")
            documents.append((path, document))
            accounts.append(match.group())
        except (OSError, UnicodeError, json.JSONDecodeError, KeyError, TypeError, ValueError) as error:
            errors.append((path, error))
            print(f"Skipped {path.name}: {error}", file=sys.stderr)
    counts = Counter(accounts)
    outputs = []
    used_names = set()
    for (path, document), account in zip(documents, accounts):
        try:
            if counts[account] == 1:
                name = f"sec-forms-{account}.tex"
            else:
                # Two review groups can assess the same control account. Keep both.
                review = path.stem.split(account, 1)[0].rstrip("_ ").split("_")[-1]
                slug = re.sub(r"[^a-z0-9]+", "-", review.lower()).strip("-") or "review"
                suffix = hashlib.sha256(path.name.encode("utf-8")).hexdigest()[:8]
                name = f"sec-forms-{account}-{slug}-{suffix}.tex"
            if name in used_names:
                raise ValueError(f"Output filename collision: {name}")
            slides = make_slides(document, path, name)
            outputs.append((FORMS / name, slides, path))
            used_names.add(name)
        except (KeyError, TypeError, ValueError) as error:
            errors.append((path, error))
            print(f"Skipped {path.name}: {error}", file=sys.stderr)
    FORMS.mkdir(parents=True, exist_ok=True)
    written = []
    for destination, slides, path in outputs:
        try:
            destination.write_text(slides, encoding="utf-8")
            written.append(destination)
            print(f"Wrote: {destination}")
        except OSError as error:
            errors.append((path, error))
            print(f"Skipped {path.name}: {error}", file=sys.stderr)
    injector = OUTPUT / "sec-forms.tex"
    injector_text, summarized, missing = make_injector(accounts, written)
    injector.write_text(injector_text, encoding="utf-8")
    print(f"Wrote: {injector}")
    print(f"JSON files: {len(files)}; forms analyzed: {len(accounts)}; "
          f"slides written: {len(written)}; selected: {summarized}; skipped: {len(errors)}; "
          f"curated entries missing: {missing}")
    print_provenance()


if __name__ == "__main__":
    main()


